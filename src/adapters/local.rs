#[cfg(test)]
mod tests {
    use super::*;
    use crate::adapters::Resettable;
    use crate::counters::Observable;
    use crate::labeled_group;
    use std::sync::Arc;
    use std::thread;

    fn assert_send_sync<T: Send + Sync>() {}

    #[test]
    fn test_local_is_send_and_sync() {
        assert_send_sync::<Local<'static, Monotone>>();
        assert_send_sync::<Local<'static, Unsigned>>();
        assert_send_sync::<Local<'static, Signed>>();
        assert_send_sync::<Local<'static, Minimum>>();
        assert_send_sync::<Local<'static, Maximum>>();
        assert_send_sync::<Local<'static, Average>>();
        assert_send_sync::<Local<'static, Rate>>();
    }

    #[test]
    fn test_monotone_flush_and_drop() {
        let c = Monotone::new().with_name("pkts");
        {
            let mut local = c.local();
            assert!(!local.has_pending());
            assert_eq!(local.pending(), 0);

            for _ in 0..100 {
                local.incr();
            }
            // Not visible globally before flush!
            assert_eq!(c.value().as_u64(), 0);
            assert!(local.has_pending());
            assert_eq!(local.pending(), 100);

            local.flush();
            assert_eq!(c.value().as_u64(), 100);
            assert!(!local.has_pending());
            assert_eq!(local.pending(), 0);

            // Second batch flushed automatically on Drop
            local.add(55);
            assert_eq!(c.value().as_u64(), 100);
        }
        assert_eq!(c.value().as_u64(), 155);
    }

    #[test]
    fn test_unsigned_net_negative_batch_and_discard() {
        let c = Unsigned::new();
        c.add(100);

        {
            let mut local = c.local();
            local.sub(30);
            local.add(10); // net -20 inside batch!
            assert!(local.has_pending());
        }
        assert_eq!(c.value().as_u64(), 80);

        {
            let mut local = c.local();
            local.add(999);
            local.discard();
            assert!(!local.has_pending());
        }
        assert_eq!(c.value().as_u64(), 80);
    }

    #[test]
    fn test_signed_and_resettable_deref() {
        let c = Resettable::new(Signed::new());
        {
            let mut local = c.local();
            local.add(50);
            local.sub(12);
            local.decr();
            assert_eq!(local.pending(), 37);
        }
        assert_eq!(c.value().as_i64(), 37);
        assert_eq!(c.value().as_i64(), 0);
    }

    #[test]
    fn test_minimum_and_maximum_batching_including_zero_and_empty() {
        let min_c = Minimum::new();
        let max_c = Maximum::new();

        // Dropping untouched proxies must leave trackers unobserved (None)!
        {
            let _min_l = min_c.local();
            let _max_l = max_c.local();
        }
        assert_eq!(min_c.get(), None);
        assert_eq!(max_c.get(), None);

        // Batch observing 0 and other values
        {
            let mut min_l = min_c.local();
            let mut max_l = max_c.local();
            assert_eq!(min_l.pending(), None);
            assert_eq!(max_l.pending(), None);

            for v in [50, 12, 0, 99, 42] {
                min_l.observe(v);
                max_l.observe(v);
            }
            assert_eq!(min_l.pending(), Some(0));
            assert_eq!(max_l.pending(), Some(99));
            assert_eq!(min_c.get(), None);
            assert_eq!(max_c.get(), None);
        }
        assert_eq!(min_c.get(), Some(0));
        assert_eq!(max_c.get(), Some(99));
    }

    #[test]
    fn test_average_and_rate_batching() {
        let avg = Average::new();
        let rate = Rate::new();

        {
            let mut avg_l = avg.local();
            let mut rate_l = rate.local();
            for v in [10, 20, 30, 40] {
                avg_l.observe(v);
                rate_l.incr();
            }
            assert_eq!(avg_l.pending(), (100, 4));
            assert_eq!(rate_l.pending(), 4);
            let debug_str = format!("{avg_l:?}");
            assert!(debug_str.contains("Local"));
        }

        assert_eq!(avg.average(), Some(25));
        assert_eq!(avg.average_f64(), Some(25.0));
        assert_eq!(rate.total_value(), 4);
    }

    #[test]
    fn test_labeled_group_local_proxy() {
        labeled_group!(
            ProtoStats,
            "packets_by_proto",
            "proto",
            tcp: "tcp": Monotone,
            udp: "udp": Monotone,
            icmp: "icmp": Monotone,
        );

        assert_send_sync::<Local<'static, ProtoStats>>();

        let stats = ProtoStats::new();
        {
            let mut local = stats.local();
            assert!(!local.has_pending());
            assert_eq!(local.counter().metric_name(), "packets_by_proto");

            for i in 0..60 {
                if i % 3 == 0 {
                    local.udp.incr();
                } else {
                    local.tcp.incr();
                }
            }
            // icmp was never touched!
            assert!(local.has_pending());
            assert!(local.tcp.has_pending());
            assert!(local.udp.has_pending());
            assert!(!local.icmp.has_pending());
            assert_eq!(stats.total().as_u64(), 0);

            local.flush();
            assert!(!local.has_pending());
            assert_eq!(stats.tcp.value().as_u64(), 40);
            assert_eq!(stats.udp.value().as_u64(), 20);
            assert_eq!(stats.icmp.value().as_u64(), 0);

            // Test discard on group
            local.tcp.add(500);
            local.discard();
            assert!(!local.has_pending());

            // Test Drop flush on group
            local.icmp.add(7);
        }

        assert_eq!(stats.tcp.value().as_u64(), 40);
        assert_eq!(stats.udp.value().as_u64(), 20);
        assert_eq!(stats.icmp.value().as_u64(), 7);
    }

    #[test]
    fn test_multithreaded_batch_workers() {
        let counter = Arc::new(Unsigned::new());
        let mut handles = Vec::new();

        for _ in 0..8 {
            let c = Arc::clone(&counter);
            handles.push(thread::spawn(move || {
                let mut local = c.local();
                for batch in 0..100 {
                    for _ in 0..256 {
                        local.incr();
                    }
                    if batch % 10 == 0 {
                        local.flush();
                    }
                }
                // Remaining 9 batches flushed on Drop!
            }));
        }

        for h in handles {
            h.join().unwrap();
        }

        assert_eq!(counter.value().as_u64(), 8 * 100 * 256);
    }
}
