//! Local batch accumulator (`Local<'a, C>`) for amortizing counter updates across batches.
//!
//! While `contatori`'s sharded counters eliminate cross-core cache-line bouncing, updating an
//! atomic counter on every individual event in a tight batch loop still incurs a `thread_local!`
//! lookup and an atomic read-modify-write instruction (`lock add` / `ldadd`) per event,
//! preventing register promotion and loop vectorization.
//!
//! [`Local<'a, C>`](Local) buffers updates in plain non-atomic memory (typically kept in a CPU
//! register across the batch loop) and flushes the accumulated delta to the underlying sharded
//! counter **once per batch** — either explicitly via [`Local::flush()`] or automatically when
//! the [`Local`] guard is dropped.
//!
//! If no updates were recorded during a batch (`!has_pending()`), [`flush()`](Local::flush) and
//! `Drop` perform **zero** atomic operations and do not touch any cache line.
//!
//! # Examples
//!
//! ```rust
//! use contatori::{Monotone, Observable};
//!
//! static PACKETS: Monotone = Monotone::new().with_name("rx_packets_total");
//!
//! fn process_batch(batch_len: usize) {
//!     let mut local_pkts = PACKETS.local();
//!     for _ in 0..batch_len {
//!         local_pkts.incr(); // plain non-atomic register increment!
//!     }
//!     // Automatically flushed to `PACKETS` here when `local_pkts` is dropped
//!     // (or call `local_pkts.flush()` explicitly in long-lived loops).
//! }
//!
//! process_batch(64);
//! assert_eq!(PACKETS.value().as_u64(), 64);
//! ```

