/// Marker trait for counters and [`labeled_group!`](crate::labeled_group) structs that can be
/// buffered locally via [`Local`].
///
/// This trait is *sealed* and automatically implemented for all built-in counter types and
/// structs generated by [`labeled_group!`](crate::labeled_group).
pub trait Batchable: sealed::Batchable {
    /// Creates a new [`Local`] batch proxy for `self`.
    #[must_use]
    #[inline]
    fn local(&self) -> Local<'_, Self>
    where
        Self: Sized,
    {
        Local::new(self)
    }
}

impl<T: sealed::Batchable> Batchable for T {}

/// A thread-local / batch-scoped write proxy for a sharded counter or [`labeled_group!`](crate::labeled_group).
///
/// Updates performed on `Local<'a, C>` mutate plain non-atomic state (`&mut self`) with zero
/// `thread_local!` lookups and zero atomic instructions. Accumulated deltas are synchronized
/// back to `C` when [`flush()`](Self::flush) is called or automatically when `Local` is dropped.
///
/// Because `Local<'a, C>` holds `&'a C` and resolves the current thread's shard only inside
/// [`flush()`](Self::flush), `Local<'a, C>` is both `Send` and `Sync` (for all built-in counters
/// and groups) and can be held safely across `.await` points in multi-threaded async tasks.
pub struct Local<'a, C: Batchable> {
    counter: &'a C,
    acc: C::Acc<'a>,
}

impl<'a, C: Batchable> Local<'a, C> {
    /// Creates a new empty [`Local`] accumulator referencing `counter`.
    #[must_use]
    #[inline]
    pub fn new(counter: &'a C) -> Self {
        let acc = counter.new_acc();
        Self { counter, acc }
    }

    /// Internal `const` constructor used by inherent `.local()` methods and `labeled_group!`.
    #[doc(hidden)]
    #[must_use]
    #[inline]
    pub const fn __from_parts(counter: &'a C, acc: C::Acc<'a>) -> Self {
        Self { counter, acc }
    }

    /// Returns a shared reference to the underlying global counter or group.
    #[must_use]
    #[inline]
    pub const fn counter(&self) -> &'a C {
        self.counter
    }

    /// Returns `true` if there are buffered updates waiting to be flushed.
    #[must_use]
    #[inline]
    pub fn has_pending(&self) -> bool {
        C::has_pending_acc(&self.acc)
    }

    /// Flushes any buffered updates to the underlying counter and resets the local state.
    ///
    /// If [`has_pending()`](Self::has_pending) is `false`, this is a pure no-op (no TLS lookup,
    /// no atomic operations).
    #[inline]
    pub fn flush(&mut self) {
        self.counter.flush_acc(&mut self.acc);
    }

    /// Discards all buffered updates without applying them to the underlying counter.
    #[inline]
    pub fn discard(&mut self) {
        C::discard_acc(&mut self.acc);
    }
}

impl<C: Batchable> Drop for Local<'_, C> {
    #[inline]
    fn drop(&mut self) {
        self.counter.flush_acc(&mut self.acc);
    }
}

impl<'a, C> Debug for Local<'a, C>
where
    C: Batchable + Debug,
    C::Acc<'a>: Debug,
{
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Local")
            .field("counter", &self.counter)
            .field("pending", &self.acc)
            .finish()
    }
}

impl<'a, G: sealed::BatchableGroup> Deref for Local<'a, G> {
    type Target = G::Acc<'a>;

    #[inline]
    fn deref(&self) -> &Self::Target {
        &self.acc
    }
}

impl<'a, G: sealed::BatchableGroup> DerefMut for Local<'a, G> {
    #[inline]
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.acc
    }
}

// ============================================================================
// Monotone<SHARDS>
// ============================================================================

impl<const SHARDS: usize> sealed::Batchable for Monotone<SHARDS> {
    type Acc<'a> = u64;

    #[inline]
    fn new_acc(&self) -> u64 {
        0
    }

    #[inline]
    fn has_pending_acc(acc: &u64) -> bool {
        *acc != 0
    }

    #[inline]
    fn flush_acc(&self, acc: &mut u64) {
        let delta = *acc;
        if delta != 0 {
            self.add(delta);
            *acc = 0;
        }
    }

    #[inline]
    fn discard_acc(acc: &mut u64) {
        *acc = 0;
    }
}

impl<const SHARDS: usize> Local<'_, Monotone<SHARDS>> {
    /// Buffers an addition of `value` locally.
    #[inline]
    pub fn add(&mut self, value: u64) {
        self.acc = self.acc.wrapping_add(value);
    }

    /// Buffers an increment of `1` locally.
    #[inline]
    pub fn incr(&mut self) {
        self.add(1);
    }

    /// Returns the currently buffered unflushed delta.
    #[must_use]
    #[inline]
    pub const fn pending(&self) -> u64 {
        self.acc
    }
}

